const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { execFileSync } = require('node:child_process');

(async () => {
    execFileSync(process.env.PDF_TEST_PYTHON || 'python', [path.join(__dirname, 'make_pdf_fixtures.py')], { stdio: 'inherit' });
    const root = path.resolve(__dirname, '..');
    const server = http.createServer((req, res) => {
        const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://local').pathname));
        if (!file.startsWith(root + path.sep)) { res.writeHead(403); return res.end(); }
        const mime = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.wasm': 'application/wasm' };
        res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream');
        const stream = fs.createReadStream(file);
        stream.on('error', () => { res.writeHead(404); res.end(); }); stream.pipe(res);
    });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const browser = await chromium.launch({ headless: true, channel: 'chrome' });
    try {
        const base = `http://127.0.0.1:${server.address().port}`;
        const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
        const errors = [], requests = [];
        page.on('pageerror', error => errors.push(error.message));
        page.on('request', req => requests.push({ url: req.url(), method: req.method() }));
        await page.goto(base + '/paper_shredder_academic_decompression_simulator.html');
        // Freeze only the game loop. PDF.js still needs the browser's animation frames.
        await page.evaluate(() => { gameLoop = () => {}; pdfViewMode = 'single'; }); await page.waitForTimeout(80);
        const fixture = name => path.join(__dirname, '.tmp', name);
        const openImport = () => page.locator('#openCustomModalBtn').click();
        const ready = index => page.waitForFunction(index => currentTemplateKey === 'pdf' && currentPage === index && !!currentPdfPageData, index);
        await openImport(); await page.locator('#pdfFileInput').setInputFiles(fixture('manuscript.pdf'));
        await ready(0);
        assert.equal(await page.evaluate(() => pageCount()), 6);
        assert.equal(await page.locator('#customModal').isVisible(), false);
        assert(await page.evaluate(() => wordBodies.some(w => w.text.includes('Research')) && wordBodies.some(w => w.text === '中')));
        assert.equal(await page.evaluate(() => currentPdfPageData.scanned), false);
        assert(await page.evaluate(() => currentPdfPageData.pages[0].data.height >= 2900), 'PDF source should use a high resolution canonical raster');
        assert(await page.evaluate(() => Math.abs(paperRect.w / paperRect.h - 595 / 842) < .01));
        await page.evaluate(() => { renderScene(); });
        await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-original.png') });
        await page.evaluate(() => { damageWordBody(wordBodies[0], 100, -50, true); renderScene(); });
        await page.locator('#nextPageBtn').click(); await ready(1);
        assert(await page.evaluate(() => paperRect.w / paperRect.h > 1.4));
        assert(await page.evaluate(() => wordBodies.some(w => w.text.includes('Landscape'))));
        // Multiple in-flight page renders must never replace the final selected page.
        await page.evaluate(() => { changePage(1); changePage(1); changePage(1); }); await ready(4);
        assert.equal(await page.evaluate(() => currentPdfPageData.scanned), true);
        assert(await page.evaluate(() => wordBodies.length > 100 && wordBodies.every(w => w.type === 'pdfGraphic')));
        await page.evaluate(() => { slamHammer(paperRect.x + paperRect.w / 2, paperRect.y + paperRect.h / 2, 1); renderScene(); });
        assert(await page.evaluate(() => wordBodies.some(w => w.state === 'obliterated')));
        await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-scan-damage.png') });
        await page.evaluate(() => changePage(1)); await ready(5);
        assert(await page.locator('#nextPageBtn').isDisabled());
        assert(await page.evaluate(() => wordBodies.some(w => w.text === 'LastPage')));
        await page.evaluate(() => changePage(-5)); await ready(0);
        assert.equal(await page.evaluate(() => wordBodies[0].state), 'obliterated', 'original page damage survives cache eviction');
        await page.setViewportSize({ width: 1000, height: 850 }); await page.waitForTimeout(100); await ready(0);
        assert.equal(await page.evaluate(() => wordBodies[0].state), 'obliterated');
        assert(await page.evaluate(() => wordBodies.every(w => Number.isFinite(w.x) && Number.isFinite(w.w))));
        await page.evaluate(() => { triggerRewind(); for (let i = 0; i < 120; i++) updateSimulation(1 / 60); renderScene(); });
        assert(await page.evaluate(() => wordBodies.every(w => w.state === 'formatted')));
        await page.locator('#paperSelect').selectOption('cvpr'); assert.equal(await page.evaluate(() => currentTemplateKey), 'cvpr');
        await page.locator('#paperSelect').selectOption('pdf'); await ready(0);
        await openImport(); await page.locator('#pdfFileInput').setInputFiles({ name: 'not-a-pdf.pdf', mimeType: 'application/pdf', buffer: Buffer.from('plain text') });
        await page.waitForFunction(() => document.getElementById('importStatus').classList.contains('error'));
        assert.equal(await page.evaluate(() => importedPdf.doc.numPages), 6, 'a failed import keeps the existing document');
        assert.equal(await page.locator('#pdfFileInput').isDisabled(), false);
        await page.locator('#pdfFileInput').setInputFiles(fixture('broken.pdf'));
        await page.waitForFunction(() => document.getElementById('importStatus').classList.contains('error'));
        assert.equal(await page.locator('#applyCustomBtn').isDisabled(), false);
        await page.locator('#pdfFileInput').setInputFiles(fixture('encrypted.pdf'));
        await page.locator('#pdfPasswordInput').waitFor({ state: 'visible' });
        await page.locator('#pdfPasswordInput').fill('wrong'); await page.locator('#pdfPasswordBtn').click();
        await page.waitForFunction(() => document.getElementById('importStatus').textContent.includes('密码不正确'));
        await page.locator('#pdfPasswordInput').fill('secret'); await page.locator('#pdfPasswordInput').press('Enter'); await ready(0);
        await page.waitForFunction(() => importedPdf.name === 'encrypted.pdf');
        assert.equal(await page.locator('#customModal').isVisible(), false);
        // Cancel a password prompt, then import the same file again.
        await openImport(); await page.locator('#pdfFileInput').setInputFiles(fixture('encrypted.pdf'));
        await page.locator('#pdfPasswordInput').waitFor({ state: 'visible' }); await page.locator('#cancelCustomBtn').click();
        assert.equal(await page.evaluate(() => pdfImportTask), null);
        await openImport(); await page.locator('#pdfFileInput').setInputFiles(fixture('manuscript.pdf'));
        await page.waitForFunction(() => importedPdf.name === 'manuscript.pdf' && !document.getElementById('customModal').classList.contains('flex'));
        await ready(0);
        // The expanded stage, dual-page mode, and per-page image/text destruction.
        await page.setViewportSize({ width: 1920, height: 1080 }); await page.waitForTimeout(100); await ready(0);
        await page.locator('#viewModeBtn').click();
        await page.waitForFunction(() => currentPdfPageData?.pages.length === 2);
        assert.equal(await page.locator('#pageIndicator').innerText(), '01–02 / 06');
        assert(await page.evaluate(() => paperRect.w > W * .8 && paperRect.h > H * .8));
        assert(await page.evaluate(() => PLAYER_SCALE === .62 && stickman.height < 35));
        assert.equal(await page.locator('#sanityValue, #destroyedCount, #reviewerStatus, #fpsCounter, header, footer').count(), 0);
        assert(!/SANITY|已粉碎|Reviewer|WASD|FPS/.test(await page.locator('body').innerText()));
        await page.evaluate(() => renderScene());
        await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-spread.png') });
        const hit = await page.evaluate(() => {
            clearTransientEffects(); selectWeapon(2);
            const page = currentPdfPageData.pages[0];
            const target = wordBodies.find(w => w.pageIndex === 0 && w.type === 'pdfGraphic' && w.sy > page.data.height * .8);
            if (!target) throw Error('The original PDF figure must have destructible fragments');
            stickman.x = target.x - 85; stickman.y = target.y + 42 * PLAYER_SCALE; stickman.aimAngle = 0;
            for (let i = 0; i < 10; i++) fireWeapon(.016);
            clearAction();
            const figures = wordBodies.filter(w => w.type === 'pdfGraphic' && w.state !== 'formatted').length;
            const keys = [0, 1].map(index => {
                const word = wordBodies.find(w => w.pageIndex === index && w.type === 'pdfText');
                damageWordBody(word, 0, 0, true);
                return { pageIndex: index, sx: word.sx, sy: word.sy };
            });
            renderScene(); return { figures, keys };
        });
        assert(hit.figures > 0, 'lasers must damage original images in text PDFs');
        await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-figure-damage.png') });
        await page.locator('#viewModeBtn').click(); await ready(0);
        const destroyed = async key => page.evaluate(key => wordBodies.find(w => w.pageIndex === key.pageIndex && w.sx === key.sx && w.sy === key.sy)?.state, key);
        assert.equal(await destroyed(hit.keys[0]), 'obliterated');
        await page.locator('#nextPageBtn').click(); await ready(1);
        assert.equal(await destroyed(hit.keys[1]), 'obliterated');
        await page.locator('#viewModeBtn').click(); await ready(0);
        assert.equal(await destroyed(hit.keys[0]), 'obliterated'); assert.equal(await destroyed(hit.keys[1]), 'obliterated');
        await page.evaluate(() => changePage(4)); await ready(4);
        assert.equal(await page.locator('#pageIndicator').innerText(), '05–06 / 06');
        assert(await page.locator('#nextPageBtn').isDisabled());
        await page.evaluate(() => changePage(-4)); await ready(0);
        assert.equal(await destroyed(hit.keys[0]), 'obliterated');
        assert.equal(await destroyed(hit.keys[1]), 'obliterated');
        const stampWords = await page.evaluate(() => {
            clearTransientEffects(); const words = [], original = ctx.fillText, originalRect = ctx.strokeRect; let frames = 0;
            ctx.fillText = function(text, ...args) { words.push(text); return original.call(this, text, ...args); };
            ctx.strokeRect = function(...args) { frames++; return originalRect.call(this,...args); };
            triggerForceAccept(); renderScene(); ctx.fillText = original; ctx.strokeRect = originalRect; return {words,frames};
        });
        assert.deepEqual(stampWords, {words:['Accept'],frames:1});
        await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-accept.png') });
        await page.locator('#viewModeBtn').click(); await ready(0);
        // Scanned and blank pages are both selectable; mobile retains PDF aspect ratio.
        await page.evaluate(() => changePage(3)); await ready(3);
        assert.equal(await page.evaluate(() => currentPdfPageData.scanned), true);
        await page.evaluate(() => changePage(-1)); await ready(2);
        assert(await page.evaluate(() => wordBodies.some(w => w.text.includes('Rotated'))));
        await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(100); await ready(2);
        assert(await page.evaluate(() => paperRect.x >= getStageRect().x && paperRect.y + paperRect.h <= getStageRect().y + getStageRect().h + 1));
        await page.evaluate(() => renderScene()); await page.screenshot({ path: path.join(__dirname, '.tmp', 'pdf-mobile.png') });
        await page.evaluate(() => { pdfViewMode = 'auto'; });
        await page.setViewportSize({ width: 1920, height: 1080 }); await page.waitForTimeout(100); await ready(2);
        assert.equal(await page.evaluate(() => currentPdfPageData.pages.length), 2, 'wide screens should automatically use a spread');
        assert(requests.every(r => r.method === 'GET' && (r.url.startsWith(base) || r.url.startsWith('blob:') || r.url.startsWith('data:'))), 'PDF data must stay local');
        assert.deepEqual(errors, []);
        const retina = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:2});
        retina.on('pageerror',error=>errors.push(error.message));
        await retina.goto(base+'/paper_shredder_academic_decompression_simulator.html');
        await retina.evaluate(()=>{gameLoop=()=>{};pdfViewMode='single';});
        await retina.locator('#openCustomModalBtn').click(); await retina.locator('#pdfFileInput').setInputFiles(fixture('manuscript.pdf'));
        await retina.waitForFunction(()=>!!currentPdfPageData);
        assert(await retina.evaluate(()=>canvas.width===W*2&&canvas.height===H*2&&pixelRatio===2&&ctx.getTransform().a===2));
        await retina.evaluate(()=>renderScene()); await retina.screenshot({path:path.join(__dirname,'.tmp','pdf-retina.png')});
        assert.deepEqual(errors,[]);
        console.log('PASS: minimal side rails + enlarged stage + dual-page state/cache/navigation + smaller player + destructible PDF figures + accept-only stamp + local PDF/CJK/rotation/scans/password/error handling');
    } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exit(1); });
